// The site's colours are Toil UI Plain's, dark scheme (#442): this reads
// ui/themes/plain/theme.json and writes src/styles/plain.generated.css, which
// global.css imports and derives every other role from. `npm run dev` and
// `npm run build` run it first, and test/brand-sync.test.ts fails when the
// committed file isn't what this would write, so the two can't drift.
//
// A palette kept in two places by hand is a reconciliation meeting with a
// standing invite. This keeps it in one.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const THEME = join(here, '..', '..', 'ui', 'themes', 'plain', 'theme.json');
export const OUT = join(here, '..', 'src', 'styles', 'plain.generated.css');

/** Plain's dark scheme key, then the site token it becomes. The accent is written as RGB so glows can tint it. */
const TOKENS = [
  ['bg', '--color-bg'],
  ['surface', '--color-surface'],
  ['raised', '--color-surface-raised'],
  ['ink', '--color-ink'],
  ['muted', '--color-muted'],
  ['line', '--color-line'],
  ['accent', '--rgb-accent'],
  ['accentInk', '--color-accent-ink'],
  ['focus', '--color-focus'],
  ['ok', '--color-ok'],
  ['warn', '--color-warn'],
  ['danger', '--color-danger'],
];

const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(', ');

/** The generated stylesheet for a theme.json's text. */
export function plainTokens(themeJson) {
  const dark = JSON.parse(themeJson).schemes?.dark;
  if (!dark) throw new Error('ui/themes/plain/theme.json has no dark scheme');
  const lines = TOKENS.map(([key, token]) => {
    const value = dark[key];
    if (!/^#[0-9a-f]{6}$/i.test(value ?? '')) throw new Error(`Plain's dark ${key} is not a six-digit hex colour: ${value}`);
    return `  ${token}: ${token.startsWith('--rgb-') ? rgb(value) : value.toLowerCase()};`;
  });
  return [
    '/* Generated by site/scripts/plain-tokens.mjs from ui/themes/plain/theme.json',
    '   (the dark scheme). Change the theme, not this file. */',
    ':root {',
    ...lines,
    '}',
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, plainTokens(readFileSync(THEME, 'utf8')));
}
