// Writes src/areas.generated.ts: one import per src/areas/<area>/index.ts.
//
// Areas register by existing, not by editing a shared list. Twenty areas built
// in parallel would otherwise all edit the same lines of one registry file and
// conflict with each other in every possible order. The output is gitignored
// and rebuilt before typecheck, build and tests, so it can't go stale.
// A shared sign-up sheet works perfectly until the second person arrives.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { generateWorker } from './gen-worker.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const areasDir = join(root, 'src', 'areas');
const out = join(root, 'src', 'areas.generated.ts');
const skillsDir = join(root, 'skills', 'toil');
const pagesOut = join(root, 'src', 'skill-pages.generated.ts');
const themesDir = join(root, 'ui', 'themes');
const cuesOut = join(root, 'src', 'welcome', 'themes', 'moments.generated.ts');

export async function generate() {
  const dirs = readdirSync(areasDir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(areasDir, d.name, 'index.ts')))
    .map((d) => d.name)
    .sort();
  const lines = [
    '// Generated by scripts/gen-areas.mjs from src/areas/*/index.ts. Not committed; do not edit.',
    "import type { AreaModule } from './core/area-module.js';",
    ...dirs.map((d, i) => `import * as m${i} from './areas/${d}/index.js';`),
    '',
    `export const modules: AreaModule[] = [${dirs.map((_, i) => `m${i}`).join(', ')}];`,
    '',
  ];
  const content = lines.join('\n');
  if (!existsSync(out) || readFileSync(out, 'utf8') !== content) writeFileSync(out, content);
  generateSkillPages();
  generateSplashCues();
  await generateWorker();
  return dirs;
}

/**
 * Writes src/skill-pages.generated.ts: every file of the distributed skill
 * (skills/toil/*.md). `skillFiles` is the whole skill, SKILL.md included,
 * which `toil skill install` writes into an agent's skills folder; `skillPages`
 * is each page but the index, which toil mcp serves as toil://skill/<name>.
 * Built in rather than read from disk, so the bundle stays one file and the
 * skill it installs is always the one it shipped with. Line endings are LF
 * whatever the checkout has.
 */
function generateSkillPages() {
  const files = readdirSync(skillsDir)
    .filter((f) => f.endsWith('.md'))
    .sort()
    .map((f) => [f, readFileSync(join(skillsDir, f), 'utf8').replace(/\r\n/g, '\n')]);
  const lines = [
    '// Generated by scripts/gen-areas.mjs from skills/toil/*.md. Not committed; do not edit.',
    'export const skillFiles: Readonly<Record<string, string>> = {',
    ...files.map(([name, text]) => `  ${JSON.stringify(name)}: ${JSON.stringify(text)},`),
    '};',
    '',
    'export const skillPages: Readonly<Record<string, string>> = Object.fromEntries(',
    "  Object.entries(skillFiles).flatMap(([file, text]) => (file === 'SKILL.md' ? [] : [[file.slice(0, -3), text] as const])),",
    ');',
    '',
  ];
  const content = lines.join('\n');
  if (!existsSync(pagesOut) || readFileSync(pagesOut, 'utf8') !== content) writeFileSync(pagesOut, content);
}

/**
 * Writes src/welcome/themes/moments.generated.ts: each Toil UI theme's splash
 * cues (#419's `moments.splash`: the motif the art arrives with and its line),
 * read from ui/themes/<name>/theme.json, so the terminal splash plays the
 * theme's own cues rather than a second copy of them (#427). Only the cues,
 * never art or a path: the terminal draws its own braille.
 */
export function splashCues() {
  const cues = {};
  for (const d of readdirSync(themesDir, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort()) {
    const file = join(themesDir, d, 'theme.json');
    if (!existsSync(file)) continue;
    const splash = JSON.parse(readFileSync(file, 'utf8')).moments?.splash;
    cues[d] = splash ? { ...(typeof splash.motif === 'string' ? { motif: splash.motif } : {}), ...(typeof splash.line === 'string' ? { line: splash.line } : {}) } : {};
  }
  return cues;
}

function generateSplashCues() {
  const content = [
    '// Generated by scripts/gen-areas.mjs from ui/themes/*/theme.json (moments.splash). Not committed; do not edit.',
    'export interface SplashCue {',
    '  motif?: string;',
    '  line?: string;',
    '}',
    '',
    `export const SPLASH_CUES: Readonly<Record<string, SplashCue>> = ${JSON.stringify(splashCues(), null, 2)};`,
    '',
  ].join('\n');
  if (!existsSync(cuesOut) || readFileSync(cuesOut, 'utf8') !== content) writeFileSync(cuesOut, content);
}

/** Vitest global setup: generate before any test file imports the registry. */
export default async function setup() {
  await generate();
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await generate();
