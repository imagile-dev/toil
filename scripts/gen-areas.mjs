// Writes src/areas.generated.ts: one import per src/areas/<area>/index.ts.
//
// Areas register by existing, not by editing a shared list. Twenty areas built
// in parallel would otherwise all edit the same lines of one registry file and
// conflict with each other in every possible order. The output is gitignored
// and rebuilt before typecheck, build and tests, so it can't go stale.
// A shared sign-up sheet works perfectly until the second person arrives.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const areasDir = join(root, 'src', 'areas');
const out = join(root, 'src', 'areas.generated.ts');

export function generate() {
  const dirs = readdirSync(areasDir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(areasDir, d.name, 'index.ts')))
    .map((d) => d.name)
    .sort();
  const lines = [
    '// Generated by scripts/gen-areas.mjs from src/areas/*/index.ts. Not committed; do not edit.',
    "import type { AreaModule } from './core/area-module.js';",
    ...dirs.map((d, i) => `import * as m${i} from './areas/${d}/index.js';`),
    '',
    `export const modules: AreaModule[] = [${dirs.map((_, i) => `m${i}`).join(', ')}];`,
    '',
  ];
  const content = lines.join('\n');
  if (!existsSync(out) || readFileSync(out, 'utf8') !== content) writeFileSync(out, content);
  return dirs;
}

/** Vitest global setup: generate before any test file imports the registry. */
export default function setup() {
  generate();
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) generate();
