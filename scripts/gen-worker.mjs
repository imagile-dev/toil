// Writes src/areas/util/kit/bounded-worker.generated.ts: kit/bounded-task.ts and
// the JSON Schema validator it uses, bundled into one CommonJS string that
// kit/bounded.ts evaluates in a worker thread. A worker gets this small script
// rather than the whole CLI, so it starts in milliseconds and carries nothing
// it doesn't run. Run by scripts/gen-areas.mjs before typecheck, build and
// tests; the output is gitignored, like the registry it sits beside.
// The worker's job description fits on one page, which is a first.
import { buildSync } from 'esbuild';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const entry = join(root, 'src', 'areas', 'util', 'kit', 'bounded-task.ts');
const out = join(root, 'src', 'areas', 'util', 'kit', 'bounded-worker.generated.ts');

export function generateWorker() {
  const result = buildSync({ entryPoints: [entry], bundle: true, platform: 'node', format: 'cjs', target: 'node24', minify: true, write: false, legalComments: 'none', logLevel: 'error' });
  const code = result.outputFiles[0].text;
  const content = [
    '// Generated by scripts/gen-worker.mjs from src/areas/util/kit/bounded-task.ts. Not committed; do not edit.',
    `export const WORKER_SOURCE = ${JSON.stringify(code)};`,
    '',
  ].join('\n');
  if (!existsSync(out) || readFileSync(out, 'utf8') !== content) writeFileSync(out, content);
}
