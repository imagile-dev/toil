// Draws the terminal's wordmark from the real face (#281): "toil" in Fredoka 600,
// rasterised in headless Chrome from @fontsource/fredoka and sampled onto the
// grid the splash draws with, quadrant blocks, two pixels across and two down
// per cell. A terminal cell is about twice as tall as it is wide, so a pixel is
// twice as tall as wide and the word is sampled at twice the horizontal density
// to keep Fredoka's proportions. Writes src/welcome/wordmark.ts.
//
//   node scripts/gen-wordmark.mjs            # write the file
//   node scripts/gen-wordmark.mjs --print    # show the bitmap, write nothing
//
// Then look at it in a terminal. The sampler is honest, not tasteful: any pixel
// it can't decide is decided in TUNE below, by hand, where a reviewer can see it.
// Repo tooling only; nothing here ships. A typeface was procured through the
// proper channels: we asked the font.
import { Buffer } from 'node:buffer';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { findChrome, openBrowser } from '../ui/scripts/chrome.mjs';

const root = join(import.meta.dirname, '..');
/** Pixel rows from the top of the "l" to the baseline: 8 terminal lines. */
const ROWS = 16;
/** Coverage at or above which a pixel is ink. */
const INK = 0.5;
/**
 * Hand-tuning after sampling, as [row, column, ink] in pixels. Each one says why;
 * the sampler's answer is otherwise final.
 */
const TUNE = [];

const font = readFileSync(join(root, 'node_modules/@fontsource/fredoka/files/fredoka-latin-600-normal.woff2')).toString('base64');
const page = `<!doctype html><style>@font-face{font-family:F;font-weight:600;src:url(data:font/woff2;base64,${font}) format('woff2')}</style><canvas id=c width=2400 height=900></canvas>`;

const chrome = findChrome();
if (!chrome) throw new Error('No Chrome, Edge or Chromium found. Set CHROME_PATH to one.');
const browser = await openBrowser(chrome);
let coverage;
try {
  await browser.page.goto(`data:text/html;base64,${Buffer.from(page).toString('base64')}`);
  // Draw large, find the ink's box, and return the coverage of every source pixel in it.
  coverage = await browser.page.evaluate(`(async () => {
    await document.fonts.load('600 600px F');
    const c = document.getElementById('c'), x = c.getContext('2d');
    x.fillStyle = '#000'; x.font = '600 600px F'; x.textBaseline = 'alphabetic';
    x.fillText('toil', 40, 760);
    const d = x.getImageData(0, 0, c.width, c.height).data;
    let x0 = c.width, x1 = 0, y0 = c.height, y1 = 0;
    for (let y = 0; y < c.height; y++) for (let i = 0; i < c.width; i++) if (d[(y * c.width + i) * 4 + 3] > 0) { x0 = Math.min(x0, i); x1 = Math.max(x1, i); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
    const w = x1 - x0 + 1, h = y1 - y0 + 1, alpha = [];
    for (let y = y0; y <= y1; y++) for (let i = x0; i <= x1; i++) alpha.push(d[(y * c.width + i) * 4 + 3]);
    return { w, h, alpha };
  })()`);
} finally {
  await browser.close();
}

// Sample: each pixel is (h / ROWS) source pixels tall and half that wide.
const { w, h, alpha } = coverage;
const cellH = h / ROWS;
const cellW = cellH / 2;
const cols = Math.ceil(w / cellW);
const bitmap = [];
for (let r = 0; r < ROWS; r++) {
  let line = '';
  for (let c = 0; c < cols; c++) {
    let sum = 0;
    let n = 0;
    for (let y = Math.floor(r * cellH); y < Math.min(h, Math.floor((r + 1) * cellH)); y++) {
      for (let x = Math.floor(c * cellW); x < Math.min(w, Math.floor((c + 1) * cellW)); x++) {
        sum += alpha[y * w + x] / 255;
        n++;
      }
    }
    line += n && sum / n >= INK ? '#' : '.';
  }
  bitmap.push(line);
}
for (const [r, c, ink] of TUNE) bitmap[r] = bitmap[r].slice(0, c) + (ink ? '#' : '.') + bitmap[r].slice(c + 1);
// An even width, so the word fills whole cells.
if (cols % 2) bitmap.forEach((line, i) => (bitmap[i] = `${line}.`));

if (process.argv.includes('--print')) {
  console.log(bitmap.join('\n'));
} else {
  const out = `// Generated by scripts/gen-wordmark.mjs from Fredoka 600 (@fontsource/fredoka). Don't edit by hand:
// change the script's TUNE and run it again.

/**
 * "toil" in the wordmark's face, as pixels: ${ROWS} rows, from the top of the "l" to
 * the baseline, and ${bitmap[0].length} columns, sampled at twice the horizontal density
 * because a terminal cell is twice as tall as it is wide. The splash draws two
 * pixels across and two down per cell, in quadrant blocks.
 */
export const WORDMARK: readonly string[] = [
${bitmap.map((line) => `  '${line}',`).join('\n')}
];
`;
  writeFileSync(join(root, 'src/welcome/wordmark.ts'), out);
  console.log(`src/welcome/wordmark.ts: ${ROWS} x ${bitmap[0].length} pixels, ${ROWS / 2} lines by ${bitmap[0].length / 2} columns.`);
}
